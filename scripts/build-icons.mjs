// Compiles resources/icons.json into a local SVG sprite (no CDN, works offline).
//   npm run icons
import fs from 'fs';
const set = JSON.parse(fs.readFileSync('node_modules/@iconify-json/game-icons/icons.json', 'utf8'));
const map = JSON.parse(fs.readFileSync('resources/icons.json', 'utf8'));
let symbols = '', n = 0;
for (const [key, name] of Object.entries(map)) {
  if (key.startsWith('_')) continue;
  const ic = set.icons[name];
  if (!ic) { console.error('Missing game-icons name:', name, '(for', key + ')'); process.exit(1); }
  symbols += `<symbol id="i-${key}" viewBox="0 0 512 512"><g fill="currentColor">${ic.body.replace(/fill="[^"]*"/g, '')}</g></symbol>\n`;
  n++;
}
const out = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/build-icons.mjs from resources/icons.json. Icons: game-icons.net, CC BY 3.0 (https://game-icons.net). -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols}</svg>
`;
fs.writeFileSync("public/icons.svg", out);
console.log(`Built ${n} icons → public/icons.svg`);
