// Self-hosts Figtree (latin) so the game looks right offline:  node scripts/fetch-fonts.mjs
import fs from 'fs';
fs.mkdirSync('public/fonts', { recursive: true });
fs.mkdirSync('public/css', { recursive: true });
let css = '/* Figtree (latin) — self-hosted for offline play. Generated by scripts/fetch-fonts.mjs. SIL Open Font License. */\n';
for (const w of [400, 500, 600, 700, 800, 900]) {
  const res = await fetch(`https://fonts.bunny.net/figtree/files/figtree-latin-${w}-normal.woff2`);
  if (!res.ok) throw new Error(`font ${w}: HTTP ${res.status}`);
  fs.writeFileSync(`public/fonts/figtree-latin-${w}.woff2`, Buffer.from(await res.arrayBuffer()));
  css += `@font-face { font-family: 'Figtree'; font-style: normal; font-weight: ${w}; font-display: swap; src: url(../fonts/figtree-latin-${w}.woff2) format('woff2'); unicode-range: U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD; }\n`;
}
fs.writeFileSync('public/css/fonts.css', css);
console.log('fonts ok');
