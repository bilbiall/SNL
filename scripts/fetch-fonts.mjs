// Self-hosts the game's fonts so it looks right offline:  node scripts/fetch-fonts.mjs
//   Figtree (latin) for text, Bungee for the landing-page title — both SIL Open Font License.
import fs from 'fs';
fs.mkdirSync('public/fonts', { recursive: true });
fs.mkdirSync('public/css', { recursive: true });
const RANGE = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
let css = '/* Self-hosted for offline play. Generated by scripts/fetch-fonts.mjs. SIL Open Font License. */\n';
async function get(url, file) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  fs.writeFileSync(`public/fonts/${file}`, Buffer.from(await res.arrayBuffer()));
}
for (const w of [400, 500, 600, 700, 800, 900]) {
  await get(`https://fonts.bunny.net/figtree/files/figtree-latin-${w}-normal.woff2`, `figtree-latin-${w}.woff2`);
  css += `@font-face { font-family: 'Figtree'; font-style: normal; font-weight: ${w}; font-display: swap; src: url(../fonts/figtree-latin-${w}.woff2) format('woff2'); unicode-range: ${RANGE}; }\n`;
}
await get('https://fonts.bunny.net/bungee/files/bungee-latin-400-normal.woff2', 'bungee-latin-400.woff2');
css += `@font-face { font-family: 'Bungee'; font-style: normal; font-weight: 400; font-display: swap; src: url(../fonts/bungee-latin-400.woff2) format('woff2'); unicode-range: ${RANGE}; }\n`;
fs.writeFileSync('public/css/fonts.css', css);
console.log('fonts ok');
